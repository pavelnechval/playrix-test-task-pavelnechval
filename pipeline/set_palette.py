"""Background-colour profile of whole sets: reference rows versus our chosen variants (pixel measurement).

    python -I pipeline/set_palette.py OUT_MD

For every card, the backdrop is measured as in colour_check.py: the top band and the upper side strips.
That is the wall, the sky or the plain background in every category. Per set it reports the colour family
of each card, how many cards share the set's most common family, warm vs cool, and how often neighbours
in the 5x2 window (left-right, or above-below) share a family.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

from PIL import Image  # noqa: E402

from colour_check import backdrop_family  # noqa: E402

CARDS = ROOT / "references" / "miro_v1" / "cards"
# Reference grid rows, named after the collection windows (references/miro_v1/collection_summer); row 12 is the grand set.
REF_SETS = {1: "Finals", 2: "Coolness", 3: "Beach", 4: "Road Trip", 5: "Sports", 6: "Amusement", 7: "Countrystead",
            8: "Boyscout", 9: "Music Fest", 10: "Poolside", 11: "Tour", 12: "Summer Party (grand)", 13: "Gardens",
            14: "Seafaring", 15: "Vacation", 16: "Diving"}
OURS = [("love-in-the-city", "B"), ("picture-perfect-suburbia", "A"), ("once-upon-a-garden", "A"), ("the-lost-island", "C")]
WARM = {"red", "orange", "yellow", "pink"}
SHORT = {"red": "R", "orange": "O", "yellow": "Y", "green": "G", "teal": "T", "blue": "B", "purple": "P", "pink": "K",
         "grey/dark": "-"}


def family(path: Path) -> str:
    return backdrop_family(Image.open(path))


def profile(name: str, families: list[str]) -> dict:
    counts = Counter(families)
    top, top_n = counts.most_common(1)[0]
    pairs = [(i, i + 1) for i in range(9) if i != 4] + [(i, i + 5) for i in range(5)]  # 5x2 window neighbours
    same = sum(families[a] == families[b] for a, b in pairs)
    return {"set": name, "row": " ".join(SHORT[f] for f in families[:5]) + " / " + " ".join(SHORT[f] for f in families[5:]),
            "families": len(counts), "top": f"{top} {top_n}/10", "top_n": top_n,
            "warm": sum(f in WARM for f in families), "same_neighbours": same}


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    rows = []
    for r, name in REF_SETS.items():
        rows.append(("ref", profile(name, [family(CARDS / f"r{r:02d}c{c:02d}.png") for c in range(1, 11)])))
    for slug, vid in OURS:
        plan = json.loads((ROOT / "sets" / slug / "plan.json").read_text(encoding="utf-8"))
        cards = next(v for v in plan["variants"] if v["id"] == vid)["cards"]
        rows.append(("ours", profile(f"{plan['set']} {vid}", [family(ROOT / "sets" / slug / "final" / f"{c['id']}.png") for c in cards])))
    lines = ["# Set palette profile (generated by pipeline/set_palette.py)", "",
             "Backdrop colour family per card (R red, O orange, Y yellow, G green, T teal, B blue, P purple, K pink).",
             "Order: reference sets in board-grid order (mostly, not always, the in-game window order); ours in plan order.",
             "Neighbour pairs: 13 per set (8 left-right, 5 above-below); the neighbour count depends on that order.", "",
             "| Source | Set | Cards 1-5 / 6-10 | Families | Most common | Warm backdrops | Same-colour neighbours |",
             "|---|---|---|---|---|---|---|"]
    for source, p in rows:
        lines.append(f"| {source} | {p['set']} | {p['row']} | {p['families']} | {p['top']} | {p['warm']}/10 | {p['same_neighbours']}/13 |")
    for source in ("ref", "ours"):
        group = [p for s, p in rows if s == source and "grand" not in p["set"]]
        n = len(group)
        lines.append("")
        lines.append(f"**{source}** ({n} object sets): families per set {sum(p['families'] for p in group) / n:.1f}; "
                     f"most common family covers {sum(p['top_n'] for p in group) / n:.1f}/10 cards; "
                     f"warm backdrops {sum(p['warm'] for p in group) / n:.1f}/10; "
                     f"same-colour neighbours {sum(p['same_neighbours'] for p in group) / n:.1f}/13.")
    Path(argv[0]).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
